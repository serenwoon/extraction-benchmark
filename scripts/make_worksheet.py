"""표본 JSON에서 사람이 채울 원문 파일과 작업지를 만든다.

    python scripts/make_worksheet.py
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

RUBRIC = """## 분류 5종 — 이 정의로만 판정한다

| 분류 | 정의 |
|---|---|
| `의무` | 특정 주체가 **무엇을 해야 한다**고 정한 것 |
| `금지` | **하면 안 된다** / 통행·행위를 제한하는 것 |
| `권한절차` | 행정청·기관이 무엇을 **할 수 있다**, 또는 지정·신고·발급·교육 등의 **절차**를 정한 것 |
| `정의목적` | 용어·개념·목적을 규정한 것 |
| `제재` | 벌칙·과태료·통고처분·면허 정지취소 등 **불이익 처분** |

**판정 규칙 (이게 이 벤치마크의 핵심 자산이다)**
1. **주된 것 하나만** 고른다. 여러 성격이 섞여 있어도 복수 선택하지 않는다
2. 갈리면 **그 조문이 없으면 무엇이 불가능해지는가**로 정한다
3. 의무와 제재가 같이 있으면 **의무**가 주된 것이다 (제재는 그 의무의 담보다)
4. 절차 안에 의무가 들어 있으면 **권한절차**다 (절차가 조문의 뼈대이므로)
"""


def main():
    arts = json.load(open(os.path.join(ROOT, "data", "sample_10.json"), encoding="utf-8"))

    # ── 원문 파일 (읽기 전용) ─────────────────────────────
    src = ["# 원문 — 도로교통법 표본 10건", "",
           "> 출처: 위키문헌 「대한민국 도로교통법」 (공개 자료)", "",
           "---", ""]
    for a in arts:
        src += [f"## {a['id']} — {a['label']} ({a['title']})", "", a["body"], "", "---", ""]
    open(os.path.join(ROOT, "manual", "source_10.md"), "w", encoding="utf-8", newline="\n").write("\n".join(src))

    # ── 작업지 ────────────────────────────────────────
    ws = [
        "# 작업지 — 손으로 하기 (타이머 켜고 시작)",
        "",
        "> [!important] 이 파일을 채우는 동안 AI를 일절 쓰지 않는다.",
        "> 이 측정의 전부가 **\"AI 없이 하면 얼마나 걸리나\"** 이므로, 여기서 도움을 받으면 숫자가 무의미해진다.",
        "",
        "## 하는 법",
        "",
        "1. 터미널에서 `python scripts/timer.py start`",
        "2. `manual/source_10.md`를 열고, 위에서부터 아래 표의 **분류**와 **요지** 두 칸을 채운다",
        "3. **20분이 되면 어디까지 했든 멈춘다.** 10건을 다 못 채워도 된다 — 건당 시간만 나오면 측정은 성립한다",
        "4. `python scripts/timer.py stop`",
        "",
        "**ID와 명칭은 이미 채워져 있다.** 그건 기계적인 옮겨 적기라 판단이 안 들어가고,",
        "빼고 재면 AI 쪽에 유리하게 나오지 않는다 — **이 측정을 보수적으로 만드는 선택이다.**",
        "",
        RUBRIC,
        "## 채울 표",
        "",
        "요지는 **40자 이내 한 줄**. \"무엇을 어떻게 하라고 정한 조문인가\"를 쓴다.",
        "",
        "| ID | 명칭 | 분류 | 요지 (40자 이내) |",
        "|---|---|---|---|",
    ]
    for a in arts:
        ws.append(f"| {a['id']} | {a['title']} |  |  |")
    ws += [
        "",
        "## 다 채운 뒤",
        "",
        "- [ ] `python scripts/timer.py stop` 실행했다",
        "- [ ] 채우다 **판단이 갈렸던 조문**이 있으면 여기 적어둔다 (이게 라벨링 가이드의 재료가 된다)",
        "",
        "  - ",
        "",
    ]
    open(os.path.join(ROOT, "manual", "worksheet.md"), "w", encoding="utf-8", newline="\n").write("\n".join(ws))

    print(f"생성 완료: manual/source_10.md ({sum(a['chars'] for a in arts):,}자) · manual/worksheet.md")


if __name__ == "__main__":
    main()
